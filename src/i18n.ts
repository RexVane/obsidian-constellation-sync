export type TranslationKey = keyof typeof en;

export function resolveLocale(setting: LocaleSetting): "zh-CN" | "en" {
  if (setting !== "auto") return setting;
  const documentLanguage = typeof document === "undefined" ? "" : document.documentElement.lang;
  const browserLanguage = typeof navigator === "undefined" ? "" : navigator.language;
  return `${documentLanguage} ${browserLanguage}`.toLowerCase().includes("zh") ? "zh-CN" : "en";
}

export function translator(setting: LocaleSetting): (key: TranslationKey) => string {
  const dictionary = resolveLocale(setting) === "zh-CN" ? zh : en;
  return (key) => dictionary[key];
}
